// S1-1 capability boundary. Fixture only; no model/agent process or external requests.
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, rm, readdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { startBrowserWorkspace } from "./harness.mjs";

const workspace = await mkdtemp(join(tmpdir(), "vs-relations-guard-"));
let runner;
try {
  for (const dir of ["specs", "generated/pages", "runtime"]) await mkdir(join(workspace, dir), { recursive: true });
  const project = JSON.parse(await readFile(new URL("../../test/fixtures/screen-relations-project.json", import.meta.url), "utf8"));
  project.name = "RelationGuard";
  const control = structuredClone(project.pages.login);
  control.name = "OrdinaryControl";
  control.kind = "page";
  for (const node of Object.values(control.nodes)) delete node.action;
  project.pages.control = control;
  project.pageOrder.push("control");
  const original = JSON.stringify(project);
  await writeFile(join(workspace, "specs/relations.json"), original);
  const inert = "export default function Old() { return null; }";
  await writeFile(join(workspace, "generated/pages/Old.tsx"), inert);
  runner = await startBrowserWorkspace(workspace);
  const context = await runner.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [], downloads = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("download", download => downloads.push(download));
  await page.goto(runner.url);
  await page.getByRole("button").filter({ hasText: /RelationGuard.*페이지/s }).click();
  await page.getByRole("button", { name: "File", exact: true }).waitFor();
  await page.evaluate(async () => {
    window.editor = (await import("/src/features/editor/store/editorStore.ts")).useEditorStore;
    window.ticketStore = (await import("/src/features/editor/store/ticketStore.ts")).useTicketStore;
    window.exportStore = (await import("/src/features/editor/store/exportStore.ts")).useExportStore;
    window.openTickets = (await import("/src/features/editor/ui/openTicketPanel.ts")).openTicketPanel;
  });
  for (const id of project.pageOrder.filter(id => id !== "control")) {
    const name = project.pages[id].name;
    if (id !== project.pageOrder[0]) await page.getByRole("button", { name, exact: true }).click();
    await page.evaluate(() => openTickets());
    await page.getByRole("button", { name: "에이전트에 전달", exact: true }).click();
    await page.getByText(/화면 관계.*아직 지원하지 않습니다/).waitFor();
    assert.equal(await page.evaluate(() => ticketStore.getState().running), false);
    assert.ok(await page.evaluate(() => ticketStore.getState().tickets.every(ticket => ticket.status === "pending")));
    assert.ok(!(await readdir(join(workspace, "runtime"))).includes("ticket-request.json"));
    await page.getByRole("button", { name: "File", exact: true }).click();
    await page.getByRole("menuitem", { name: "Export Code", exact: true }).click();
    await page.waitForFunction(() => exportStore.getState().status === "unsupported");
    await page.getByRole("alert").getByText(/아직 지원하지 않습니다/).waitFor();
    assert.equal(await page.getByRole("button", { name: "결과 폴더 ZIP 내려받기", exact: true }).count(), 0);
    assert.equal(await page.evaluate(() => exportStore.getState().freshness), null);
    assert.equal(await page.evaluate(() => exportStore.getState().report), null);
  }
  await page.getByRole("button", { name: "OrdinaryControl", exact: true }).click();
  await page.getByRole("button", { name: "다시 검사", exact: true }).click();
  await page.waitForFunction(() => exportStore.getState().status === "ready");
  assert.deepEqual(await page.evaluate(() => editor.getState().spec), project);
  assert.equal(await readFile(join(workspace, "generated/pages/Old.tsx"), "utf8"), inert);
  assert.deepEqual(errors, []);
  assert.equal(downloads.length, 0);
  console.log("PASS relation pages: transmission blocked, pending retained, Export unsupported/no ZIP; ordinary page still ready; imported JSON and generated bytes preserved");
} finally {
  try { await runner?.close(); } finally { await rm(workspace, { recursive: true, force: true }); }
}
