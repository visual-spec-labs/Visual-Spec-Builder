// S1-5 real controls and persistence; fixture project, no model call.
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { startBrowserWorkspace } from "./harness.mjs";
const workspace = await mkdtemp(join(tmpdir(), "vs-kind-ui-"));
let runner;
try {
  for (const dir of ["specs", "runtime", "generated"]) await mkdir(join(workspace, dir), { recursive: true });
  const project = JSON.parse(await readFile(new URL("../../test/fixtures/screen-relations-project.json", import.meta.url), "utf8"));
  project.name = "KindFlow";
  await writeFile(join(workspace, "specs/flow.json"), JSON.stringify(project));
  runner = await startBrowserWorkspace(workspace);
  const context = await runner.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(runner.url);
  await page.getByRole("button").filter({ hasText: /KindFlow.*페이지/s }).click();
  await page.evaluate(async () => { window.editor = (await import("/src/features/editor/store/editorStore.ts")).useEditorStore; });
  const state = () => page.evaluate(() => ({ spec: editor.getState().spec, history: editor.getState().history }));
  const kind = page.getByRole("combobox", { name: "화면 종류", exact: true });
  const first = await state();
  await kind.selectOption("modal");
  assert.deepEqual(await state(), first, "first page kind change rejected without history mutation");
  assert.match(await page.getByRole("alert").first().textContent(), /첫 화면/);
  const kindSection = page.getByRole("button", { name: "페이지 (Page)", exact: true }).locator("..");
  await page.getByRole("textbox", { name: "이름", exact: true }).fill("Renamed first page");
  await kindSection.getByRole("alert").waitFor({ state: "hidden" });
  await page.getByRole("textbox", { name: "이름", exact: true }).fill(project.pages.login.name);
  await kind.selectOption("modal");
  await kindSection.getByRole("alert").waitFor({ state: "visible" });
  // Actual Open of the same PageId must invalidate the old diagnostic.
  await page.getByRole("button", { name: "파일", exact: true }).click();
  await page.getByRole("menuitem", { name: "열기", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "flow.json", exact: true }).click();
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("alertdialog").getByRole("button", { name: "저장된 파일 내용으로 계속", exact: true }).click();
  await page.getByRole("alertdialog").waitFor({ state: "hidden" });
  await kindSection.getByRole("alert").waitFor({ state: "hidden" });
  await kind.selectOption("modal");
  await kindSection.getByRole("alert").waitFor({ state: "visible" });
  // Even reloading the identical spec object starts a new document session.
  await page.evaluate(() => editor.getState().loadSpec(editor.getState().spec));
  await kindSection.getByRole("alert").waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "DashboardPage", exact: true }).click();
  const target = await state(); await kind.selectOption("widget");
  assert.deepEqual(await state(), target, "incoming navigate reference blocks target kind change");
  await page.getByRole("button", { name: "새 페이지", exact: true }).click();
  const before = await state();
  const id = await page.evaluate(() => editor.getState().activePageId);
  await kind.selectOption("modal");
  assert.equal((await state()).spec.pages[id].kind, "modal");
  assert.deepEqual((await state()).spec.pageOrder, before.spec.pageOrder);
  assert.ok(await page.getByLabel("화면 종류: modal", { exact: true }).count() >= 1);
  await page.getByRole("button", { name: "되돌리기", exact: true }).click();
  assert.deepEqual((await state()).spec, before.spec);
  await page.getByRole("button", { name: "다시 실행", exact: true }).click();
  await kind.selectOption("widget");
  assert.equal((await state()).spec.pages[id].kind, "widget");
  const expected = (await state()).spec;
  const saved = page.waitForResponse(r => r.request().method() === "PUT" && r.url().includes("specs/flow.json"));
  const notice = new Promise(resolve => page.once("dialog", async d => { await d.accept(); resolve(); }));
  await page.getByRole("button", { name: "파일", exact: true }).click();
  await page.getByRole("menuitem", { name: "저장", exact: true }).click();
  assert.equal((await saved).ok(), true); await notice;
  assert.deepEqual(JSON.parse(await readFile(join(workspace, "specs/flow.json"), "utf8")), expected);
  await page.getByRole("button", { name: "파일", exact: true }).click();
  await page.getByRole("menuitem", { name: "열기", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "flow.json", exact: true }).click();
  assert.deepEqual((await state()).spec, expected);
  await page.reload();
  await page.evaluate(async () => { window.editor = (await import("/src/features/editor/store/editorStore.ts")).useEditorStore; });
  assert.deepEqual((await state()).spec, expected);
  assert.deepEqual(errors, []);
  console.log("PASS S1-5: kind controls, first/target rejection, stable ordering/badges, Undo/Redo, Save/Open/reload. Fixture only.");
} finally { try { await runner?.close(); } finally { await rm(workspace, { recursive: true, force: true }); } }
